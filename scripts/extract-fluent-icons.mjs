/**
 * Copies the Microsoft Fluent Emoji (MIT) icons used by the app into
 * public/icons/*.svg and regenerates the typed name list.
 *
 * The icon package is ~100 MB, so it is not a project dependency. To refresh:
 *   npm i --no-save @iconify-json/fluent-emoji && node scripts/extract-fluent-icons.mjs
 * (or point ICON_SOURCE at another node_modules folder).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export const ICONS = [
  // Games
  'spade-suit', 'heart-suit', 'slot-machine', 'rocket', 'bomb', 'game-die', 'joker', 'input-numbers',
  'crystal-ball', 'dragon-face', 'tiger-face', 'bullseye', 'castle', 'coin', 'admission-tickets', 'diamond-suit',
  'cherries', 'bell', 'skull', 'eagle',
  // Interface
  'wrapped-gift', 'spiral-calendar', 'tear-off-calendar', 'droplet', 'money-bag', 'glowing-star', 'trophy',
  'crown', 'sparkles', 'house', 'bust-in-silhouette', 'gem-stone', 'fire', 'bar-chart', 'hundred-points',
  'red-heart', 'chart-increasing',
  // Achievements
  'party-popper', 'world-map', 'person-running', 'top-hat', 'crescent-moon', 'high-voltage', 'comet',
  'money-with-wings', 'flexed-biceps', 'person-mage', 'sports-medal', 'four-leaf-clover',
]

const root = process.env.ICON_SOURCE ?? 'node_modules'
const set = JSON.parse(readFileSync(join(root, '@iconify-json/fluent-emoji/icons.json'), 'utf8'))
const out = new URL('../public/icons/', import.meta.url)
mkdirSync(out, { recursive: true })

for (const name of ICONS) {
  const icon = set.icons[name]
  if (!icon) throw new Error(`Missing icon: ${name}`)
  const w = icon.width ?? set.width ?? 32
  const h = icon.height ?? set.height ?? 32
  writeFileSync(new URL(`${name}.svg`, out), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${icon.body}</svg>\n`)
}

const custom = ['roulette', 'plinko', 'fortune-wheel', 'sic-bo', 'blackjack-cards']
writeFileSync(
  new URL('../src/components/ui/iconNames.ts', import.meta.url),
  `// Generated by scripts/extract-fluent-icons.mjs. Custom icons live in public/icons as well.\nexport type IconName =\n${[...ICONS, ...custom].map((n) => `  | '${n}'`).join('\n')}\n`,
)
console.log(`Wrote ${ICONS.length} icons`)
